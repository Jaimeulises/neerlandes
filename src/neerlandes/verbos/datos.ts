// Los verbos: presente (con la -t de jij y su pérdida al preguntar), perfectum
// (participio y hebben o zijn), pasado simple y verbos separables. Cada frase
// de ejemplo tiene que contener la forma que se pregunta: lo comprueban las
// pruebas.
//
// Las formas con alternativa válida se escriben con «/»: la primera es la que
// se enseña («wilt/wil»).
//
// Pendiente de revisión por una persona nativa (ver docs/revision.md).

/** ik, jij, hij o zij, wij, jullie, zij (plural). */
export type Formas = readonly [string, string, string, string, string, string];

export interface DatosVerbo {
  readonly inf: string;
  readonly es: string;
  /** Raíz del presente regular (werk, maak, praat). Si no está, van las formas a mano. */
  readonly raiz?: string;
  readonly presente?: Formas;
  /** La forma con jij detrás («werk jij?»), si no es la de ik. */
  readonly conJij?: string;
  /** Lo que sigue al verbo en las frases de presente. Sin él, el verbo no entra en presente. */
  readonly comp?: string;
  /** Si la pregunta con jij suena rara y no se practica. */
  readonly sinPregunta?: boolean;
  readonly participio?: string;
  readonly aux?: 'hebben' | 'zijn';
  /** Participio que no sigue la regla de ge- + raíz + t/d. */
  readonly irregular?: boolean;
  /** Frase en perfectum: neerlandés y español. */
  readonly perf?: readonly [string, string];
  /** Pasado simple: singular y plural. */
  readonly pasado?: readonly [string, string];
  readonly pasadoEj?: readonly [string, string];
  /** Algo que conviene saber de este verbo. */
  readonly nota?: string;
}

